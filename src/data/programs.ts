/** 알람 회로: 조건 → 자기유지 → 리셋 해제 → 알람 코일 */
function alarmRung(trigger: L[], coil: string, name: string): L[] {
  return [...trigger, ["OR", coil, "", "자기유지"], ["ANI", "X0F", "", "알람 리셋"], ["OUT", coil, "", name]];
}

/** 시퀀스 단계 전이: 지금 단계 + 넘어갈 조건 → 다음 단계 SET, 지금 단계 RST */
function seqStep(cur: string, curName: string, conds: L[], next: string, nextName: string): L[] {
  return [["LD", cur, "", curName], ...conds, ["SET", next, "", nextName], ["RST", cur, "", curName]];
}

function summary(heavy: string[], light: string[]): L[] {
  const or = (list: string[]): L[] => list.map((d, i) => [i === 0 ? "LD" : "OR", d, "", ""] as L);
  return [
    ...or(heavy),
    ["OUT", "M1", "", "중알람 있음"],
    ...or(light),
    ["OUT", "M3", "", "경알람 있음"],
    ["LD", "M1", "", ""],
    ["OR", "M3", "", ""],
    ["OUT", "Y30", "", "경광등"],
  ];
}

