import { toCsv } from "@/lib/csv";
import type { PlcProgram } from "@/lib/types";

type L = [instr: string, device: string, setValue?: string, comment?: string];
type D = [device: string, comment: string, sourceKind: string, normal: string, role?: string, checkWith?: string, where?: string];
type A = [code: string, device: string, level: "경" | "중", name: string, protect?: "안전" | "설비 보호" | "품질" | ""];

function ladderCsv(lines: L[]): string {
  let step = 0;
  const rows = lines.map(([instr, device, setValue = "", comment = ""]) => {
    const row = { 스텝: step, 명령: instr, 디바이스: device, 설정값: setValue, 코멘트: comment };
    // 스텝 수: 비교 명령 3, 타이머 OUT 4, 나머지 1 (실제 PLC와 비슷하게)
    step += /[<>=]/.test(instr) ? 3 : instr === "OUT" && /^T/.test(device) ? 4 : 1;
    return row;
  });
  return toCsv(rows, ["스텝", "명령", "디바이스", "설정값", "코멘트"]);
}

function devicesCsv(list: D[]): string {
  return toCsv(
    list.map(([device, comment, sourceKind, normal, role = "", checkWith = "", where = ""]) => ({
      디바이스: device,
      코멘트: comment,
      원천구분: sourceKind,
      평상값: normal,
      역할: role,
      확인처: checkWith,
      위치: where,
    })),
    ["디바이스", "코멘트", "원천구분", "평상값", "역할", "확인처", "위치"],
  );
}

function alarmsCsv(list: A[]): string {
  return toCsv(
    list.map(([code, device, level, name, protect = ""]) => ({ 알람번호: code, 디바이스: device, 등급: level, 알람명: name, 보호구분: protect })),
    ["알람번호", "디바이스", "등급", "알람명", "보호구분"],
  );
}

